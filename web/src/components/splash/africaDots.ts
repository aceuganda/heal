/**
 * The Heal mark, as points.
 *
 * Traced from `public/logo.png`: the logo is a dotted map of Africa, and the
 * loader redraws it dot by dot rather than fading a bitmap in. Extracted once
 * and committed rather than traced in the browser — the logo does not change
 * between page loads, and decoding a PNG to find 170 circles on every visit is
 * work the user waits through during the one moment they are already waiting.
 *
 * **Madagascar is deliberately absent.** The island read as two dots detached
 * off the south-east coast, which at this size looked like a rendering fault
 * rather than an island. The mark is the continent.
 *
 * Coordinates are normalised: x and y both run 0..1 over the mark's bounding
 * box, ordered top row first and left to right within a row, so a draw that
 * follows the array reads as the map filling in from the north. The dot radius
 * in the same units is 0.0189 — scale all three by whatever size the mark is
 * being drawn at.
 */

